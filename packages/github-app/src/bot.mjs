/**
 * EOS GitHub App Bot
 * Listens for pull_request events via webhook.
 * When a PR is opened, runs `eos consult` on changed files and posts the
 * deliverable as a PR comment.
 *
 * No external dependencies — pure Node.js HTTP server + native fetch.
 * Deploy on Railway, Fly.io, or any Node.js host.
 *
 * Required environment variables:
 *   GITHUB_TOKEN          — Personal Access Token or App token with repo:write
 *   GITHUB_WEBHOOK_SECRET — Secret for validating webhook HMAC signatures
 *   EOS_PROJECT_ROOT      — Path to local EOS System clone
 *   PORT                  — HTTP port (default: 3000)
 */

import http from "node:http";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PORT = parseInt(process.env["PORT"] ?? "3000", 10);
const WEBHOOK_SECRET = process.env["GITHUB_WEBHOOK_SECRET"] ?? "";
const GITHUB_TOKEN = process.env["GITHUB_TOKEN"] ?? "";
const EOS_ROOT = process.env["EOS_PROJECT_ROOT"] ?? path.resolve(__dirname, "../../../");

// ---------------------------------------------------------------------------
// Webhook signature validation
// ---------------------------------------------------------------------------
function validateSignature(payload, signature) {
  if (!WEBHOOK_SECRET) return true; // skip in dev without secret
  const expected = `sha256=${crypto.createHmac("sha256", WEBHOOK_SECRET).update(payload).digest("hex")}`;
  return crypto.timingSafeEqual(Buffer.from(signature), Buffer.from(expected));
}

// ---------------------------------------------------------------------------
// GitHub API: post a comment on a PR
// ---------------------------------------------------------------------------
async function postPrComment(owner, repo, prNumber, body) {
  const url = `https://api.github.com/repos/${owner}/${repo}/issues/${prNumber}/comments`;
  const response = await fetch(url, {
    method: "POST",
    headers: {
      "Authorization": `Bearer ${GITHUB_TOKEN}`,
      "Content-Type":  "application/json",
      "Accept":        "application/vnd.github+json",
      "X-GitHub-Api-Version": "2022-11-28",
      "User-Agent": "EOS-System-Bot/53.0.0",
    },
    body: JSON.stringify({ body }),
  });
  return response.ok;
}

// ---------------------------------------------------------------------------
// Run EOS consult for a PR
// ---------------------------------------------------------------------------
function runEosConsult(problem) {
  try {
    return execFileSync(process.execPath, ["bin/eos.mjs", "consult", problem], {
      cwd: EOS_ROOT,
      encoding: "utf8",
      timeout: 30_000,
    });
  } catch (err) {
    return `EOS consulting failed: ${err.message}`;
  }
}

// ---------------------------------------------------------------------------
// Format consulting output for GitHub Markdown
// ---------------------------------------------------------------------------
function formatForGitHub(deliverableText, prTitle) {
  return [
    `## 🤖 EOS System — Engineering Consulting Report`,
    `> Automatically generated for PR: **${prTitle}**`,
    ``,
    `<details>`,
    `<summary>📋 Click to expand full deliverable</summary>`,
    ``,
    deliverableText.slice(0, 65_000), // GitHub comment limit
    ``,
    `</details>`,
    ``,
    `---`,
    `*Generated by [EOS System](https://eos-system-ten.vercel.app) v53.0.0 — Engineering Operating System*`,
  ].join("\n");
}

// ---------------------------------------------------------------------------
// HTTP webhook server
// ---------------------------------------------------------------------------
const server = http.createServer(async (req, res) => {
  if (req.method === "GET" && req.url === "/health") {
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ status: "UP", service: "eos-github-bot", version: "53.0.0" }));
    return;
  }

  if (req.method !== "POST" || req.url !== "/webhook") {
    res.writeHead(404);
    res.end();
    return;
  }

  let body = "";
  req.on("data", (chunk) => { body += chunk; });
  req.on("end", async () => {
    const signature = req.headers["x-hub-signature-256"] ?? "";
    if (!validateSignature(body, signature)) {
      res.writeHead(401);
      res.end("Signature mismatch");
      return;
    }

    let event;
    try {
      event = JSON.parse(body);
    } catch {
      res.writeHead(400);
      res.end("Invalid JSON");
      return;
    }

    const eventType = req.headers["x-github-event"];

    // Only act on PR opened/synchronized events
    if (eventType === "pull_request" && (event.action === "opened" || event.action === "synchronize")) {
      res.writeHead(202);
      res.end("Accepted");

      // Run async so we don't block the webhook response
      setImmediate(async () => {
        const pr      = event.pull_request;
        const owner   = event.repository.owner.login;
        const repo    = event.repository.name;
        const prNum   = pr.number;
        const prTitle = pr.title ?? "Untitled PR";
        const prBody  = pr.body ?? "";

        const problem = `PR #${prNum}: ${prTitle}${prBody ? ` — ${prBody.slice(0, 200)}` : ""}`;
        console.log(`[EOS BOT] Running consult for PR #${prNum}: ${prTitle.slice(0, 60)}`);

        const deliverable = runEosConsult(problem);
        const comment     = formatForGitHub(deliverable, prTitle);
        const posted      = await postPrComment(owner, repo, prNum, comment);

        console.log(`[EOS BOT] Comment posted on ${owner}/${repo}#${prNum}: ${posted}`);
      });
    } else {
      res.writeHead(200);
      res.end("OK");
    }
  });
});

server.listen(PORT, () => {
  console.log(`[EOS GITHUB BOT] Listening on http://0.0.0.0:${PORT}`);
  console.log(`[EOS GITHUB BOT] Webhook endpoint: POST /webhook`);
  console.log(`[EOS GITHUB BOT] Health endpoint: GET /health`);
  console.log(`[EOS GITHUB BOT] EOS root: ${EOS_ROOT}`);
});
