#!/usr/bin/env node
/**
 * Conventional Changelog Generator — zero external dependencies.
 *
 * Parses `git log` (Conventional Commits) since the last tag and generates
 * a structured CHANGELOG.md section ready for insertion.
 *
 * Usage:
 *   node scripts/changelog.mjs               # since last tag
 *   node scripts/changelog.mjs --from v1.0   # explicit range
 *   node scripts/changelog.mjs --dry-run     # print to stdout, don't write
 */

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const fromIdx = args.indexOf("--from");
const fromRef = fromIdx >= 0 ? args[fromIdx + 1] : null;

// Determine range
let range;
if (fromRef) {
  range = `${fromRef}..HEAD`;
} else {
  try {
    const lastTag = execFileSync("git", ["describe", "--tags", "--abbrev=0"], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    }).trim();
    range = `${lastTag}..HEAD`;
  } catch {
    range = "HEAD"; // No tags: full history
  }
}

// Parse git log
let logOutput;
try {
  logOutput = execFileSync("git", ["log", range, "--pretty=format:%H|%s", "--no-merges", "--reverse"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 10 * 1024 * 1024,
  });
} catch {
  console.error("No commits found or git unavailable.");
  process.exit(0);
}

const TYPES = {
  feat: "Features",
  fix: "Bug Fixes",
  perf: "Performance",
  refactor: "Refactoring",
  docs: "Documentation",
  style: "Styles",
  test: "Tests",
  build: "Build System",
  ci: "CI/CD",
  chore: "Chores",
  revert: "Reverts",
};

const sections = {};
for (const line of logOutput.split("\n")) {
  if (!line.trim()) continue;
  const [hash, ...subjectParts] = line.split("|");
  const subject = subjectParts.join("|");

  // Parse conventional commit: type(scope)!: description
  const match = subject.match(/^(\w+)(?:\(([^)]+)\))?(!)?:\s*(.+)/);
  if (!match) continue;
  const [, type, scope, breaking, description] = match;

  const category = TYPES[type] || type;
  if (!sections[category]) sections[category] = [];
  sections[category].push({
    hash: hash.slice(0, 7),
    scope: scope || null,
    breaking: Boolean(breaking),
    description,
  });
}

// Generate Markdown
const date = new Date().toISOString().slice(0, 10);
let md = `## ${date}\n\n`;

for (const [category, entries] of Object.entries(sections)) {
  // Breaking changes first
  const breaking = entries.filter((e) => e.breaking);
  const normal = entries.filter((e) => !e.breaking);

  if (breaking.length > 0) {
    md += `### ⚠ BREAKING CHANGES — ${category}\n\n`;
    for (const e of breaking) {
      md += `- **${e.scope ? `${e.scope}: ` : ""}${e.description}** (${e.hash})\n`;
    }
    md += "\n";
  }

  if (normal.length > 0) {
    md += `### ${category}\n\n`;
    for (const e of normal) {
      md += `- ${e.scope ? `**${e.scope}:**` : ""} ${e.description} (${e.hash})\n`;
    }
    md += "\n";
  }
}

if (dryRun) {
  console.log(md);
  process.exit(0);
}

// Insert at top of CHANGELOG.md (after title if exists)
const changelogPath = path.join(root, "CHANGELOG.md");
const header =
  "# Changelog\n\nAll notable changes follow [Conventional Commits](https://www.conventionalcommits.org/).\nGenerated by `node scripts/changelog.mjs`.\n\n---\n\n";
const existing = fs.existsSync(changelogPath) ? fs.readFileSync(changelogPath, "utf8").replace(header, "") : "";
fs.writeFileSync(changelogPath, header + md + existing, "utf8");
console.log(`✅ CHANGELOG.md updated (${Object.values(sections).flat().length} entries).`);
